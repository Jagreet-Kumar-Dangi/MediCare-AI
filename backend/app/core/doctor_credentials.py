from enum import Enum


class DoctorCredentialType(str, Enum):
    MEDICAL_REGISTRATION_CERTIFICATE = "MEDICAL_REGISTRATION_CERTIFICATE"
    MEDICAL_DEGREE_CERTIFICATE = "MEDICAL_DEGREE_CERTIFICATE"
    ADDITIONAL_QUALIFICATION_CERTIFICATE = "ADDITIONAL_QUALIFICATION_CERTIFICATE"


class DoctorCredentialStatus(str, Enum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class DoctorCredentialReviewAction(str, Enum):
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
